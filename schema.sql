-- Run once in a fresh/empty Supabase project.
-- IMPORTANT: Service Role key stays server-side only.

create table if not exists public.store_settings(
 id bigint primary key default 1,
 store_name text not null default 'FLASH STORE',
 tagline text default 'Gaming & Digital Store',
 whatsapp text default '',
 discord text default '',
 instapay text default '',
 telda text default '',
 vodafone_cash text default '',
 announcement text default 'FLASH STORE',
 hero_title text default 'FLASH STORE',
 hero_text text default 'Gaming & digital products.',
 currency text not null default 'EGP',
 updated_at timestamptz not null default now()
);

create table if not exists public.categories(
 id bigint generated by default as identity primary key,
 name text not null unique,
 description text default '',
 image text default '',
 active boolean not null default true,
 show_on_home boolean not null default true,
 sort_order integer not null default 0,
 created_at timestamptz not null default now()
);

create table if not exists public.products(
 id bigint generated by default as identity primary key,
 name text not null,
 price numeric(12,2) not null default 0,
 category_id bigint references public.categories(id) on delete set null,
 platform text default 'Other',
 description text default '',
 image text default '',
 emoji text default '🎮',
 active boolean not null default true,
 featured boolean not null default false,
 sales_count integer not null default 0,
 options jsonb not null default '[]'::jsonb,
 requires_email boolean not null default false,
 requires_password boolean not null default false,
 created_at timestamptz not null default now()
);

create table if not exists public.users(
 id bigint generated by default as identity primary key,
 email text not null unique,
 name text not null,
 phone text default '',
 password_hash text not null,
 role text not null default 'client' check(role in('admin','client')),
 active boolean not null default true,
 created_at timestamptz not null default now()
);

create table if not exists public.discounts(
 id bigint generated by default as identity primary key,
 code text not null unique,
 type text not null default 'percent' check(type in('percent','fixed')),
 value numeric(12,2) not null default 0,
 active boolean not null default true,
 min_total numeric(12,2) not null default 0,
 max_uses integer not null default 0,
 used_count integer not null default 0,
 first_order_only boolean not null default false,
 created_at timestamptz not null default now()
);

-- NEW: exact products a discount applies to.
create table if not exists public.discount_products(
 discount_id bigint not null references public.discounts(id) on delete cascade,
 product_id bigint not null references public.products(id) on delete cascade,
 primary key(discount_id,product_id)
);

-- NEW: exact categories a discount applies to.
create table if not exists public.discount_categories(
 discount_id bigint not null references public.discounts(id) on delete cascade,
 category_id bigint not null references public.categories(id) on delete cascade,
 primary key(discount_id,category_id)
);

create table if not exists public.orders(
 id bigint generated by default as identity primary key,
 order_number bigint not null unique,
 user_id bigint references public.users(id) on delete set null,
 full_name text not null,
 phone text not null,
 email text not null,
 payment_method text not null,
 payment_reference text default '',
 payment_proof_url text default '',
 items jsonb not null default '[]'::jsonb,
 subtotal numeric(12,2) not null default 0,
 discount numeric(12,2) not null default 0,
 total numeric(12,2) not null default 0,
 status text not null default 'new',
 created_at timestamptz not null default now()
);

create sequence if not exists public.order_number_seq start 1001;

insert into public.store_settings(id,store_name,tagline,currency)
