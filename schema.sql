on conflict(id) do nothing;

alter table public.store_settings enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.users enable row level security;
alter table public.discounts enable row level security;
alter table public.discount_products enable row level security;
alter table public.discount_categories enable row level security;
alter table public.orders enable row level security;

drop policy if exists "public settings read" on public.store_settings;
create policy "public settings read" on public.store_settings for select using(true);

drop policy if exists "public categories read" on public.categories;
create policy "public categories read" on public.categories for select using(active=true);

drop policy if exists "public products read" on public.products;
create policy "public products read" on public.products for select using(active=true);

